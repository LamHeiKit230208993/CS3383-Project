package com.pricewatch.notifications.persistence;

import com.pricewatch.catalog.CatalogService;
import com.pricewatch.notifications.ProductTargetService;
import com.pricewatch.notifications.WatchRuleService;
import com.pricewatch.personal.PersonalDataService;
import com.pricewatch.shopping.ShoppingService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.web.servlet.MockMvc;

import java.time.Clock;
import java.time.Instant;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.time.temporal.ChronoUnit;
import java.util.List;
import java.util.Locale;

import static org.hamcrest.Matchers.containsString;
import static org.hamcrest.Matchers.not;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.when;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest(properties = {"spring.datasource.url=jdbc:h2:mem:legacy-reminder-upgrade;DB_CLOSE_DELAY=-1",
        "spring.main.web-application-type=servlet"})
@AutoConfigureMockMvc
class LegacyReminderMigrationTest {
    private static final String MILK = "P000000124";
    private static final Instant NOW = Instant.parse("2026-11-23T08:30:00Z");
    private static final Instant DUE = NOW.minus(1, ChronoUnit.DAYS);
    private static final Instant SNOOZED = NOW.plus(1, ChronoUnit.HOURS);

    @Autowired JdbcTemplate jdbc;
    @Autowired WatchRuleSchema migration;
    @Autowired WatchRuleService rules;
    @Autowired ProductTargetService events;
    @Autowired PersonalDataService personal;
    @Autowired CatalogService catalog;
    @Autowired ShoppingService shopping;
    @Autowired MockMvc mvc;
    @MockitoBean Clock clock;

    @BeforeEach void setup() {
        when(clock.instant()).thenReturn(NOW);
        personal.reset();
        catalog.importSample();
        jdbc.execute("""
                create table if not exists replenishment_reminders (
                    id bigint generated by default as identity primary key,
                    product_code varchar(80) not null references products(code),
                    quantity integer not null, interval_days integer not null,
                    selected_retailer_code varchar(80), next_due_at timestamp with time zone not null,
                    snoozed_until timestamp with time zone, paused boolean
                )
                """);
        jdbc.execute("""
                create table if not exists reminder_occurrences (
                    id bigint generated by default as identity primary key,
                    reminder_id bigint not null, product_code varchar(80) not null, quantity integer not null,
                    retailer_code varchar(80), due_at timestamp with time zone not null,
                    created_at timestamp with time zone not null, read_at timestamp with time zone,
                    snoozed_until timestamp with time zone, unique(reminder_id, due_at)
                )
                """);
        jdbc.update("delete from reminder_occurrences");
        jdbc.update("delete from replenishment_reminders");
    }

    @Test void handlesAbsentAndEmptyLegacyTables() {
        migration.afterPropertiesSet();
        // The fresh app has no dependency on tables left behind by the prior release.
        jdbc.execute("drop table reminder_occurrences");
        jdbc.execute("drop table replenishment_reminders");
        migration.afterPropertiesSet();
        assertTrue(rules.allRules().isEmpty());
        assertTrue(events.events(NOW).isEmpty());
    }

    @Test void movesRuleAndBothActiveAndOrphanHistoryWithoutDuplicates() throws Exception {
        legacyRule(7, false, SNOOZED);
        legacyRule(8, true, null);
        legacyEvent(15, 7, null, SNOOZED);
        legacyEvent(16, 999, DUE, null);
        migration.afterPropertiesSet();
        migration.afterPropertiesSet();

        var exported = personal.export(List.of(), Locale.ENGLISH);
        assertEquals(2, exported.watchRules().size());
        assertEquals(2, exported.timeAlerts().size());
        var active = exported.reminders().stream().filter(reminder -> reminder.enabled()).findFirst().orElseThrow();
        assertEquals(MILK, active.productCode());
        assertEquals(DUE, active.nextDueAt());
        assertEquals(SNOOZED, active.snoozedUntil());
        assertEquals(2, active.quantity());
        assertEquals(7, active.intervalDays());
        assertEquals("AEON", active.retailerCode());
        var currentEvent = exported.timeAlerts().stream().filter(item -> item.readAt() == null).findFirst().orElseThrow();
        assertEquals(active.id(), currentEvent.reminderId());
        assertEquals(SNOOZED, currentEvent.snoozedUntil());
        assertEquals(DUE, currentEvent.dueAt());
        assertEquals(DUE, currentEvent.createdAt());
        var orphan = exported.timeAlerts().stream().filter(item -> item.readAt() != null).findFirst().orElseThrow();
        assertNull(orphan.reminderId());
        assertEquals(DUE, orphan.readAt());
        assertTrue(exported.productPriceAlerts().isEmpty());

        mvc.perform(get("/reminders")).andExpect(redirectedUrl("/alerts"));
        mvc.perform(post("/reminders/create").param("code", MILK)).andExpect(status().isNotFound());
        mvc.perform(get("/alerts?tab=rules")).andExpect(status().isOk())
                .andExpect(content().string(containsString("2 packs · every 7 days")));
        mvc.perform(get("/alerts")).andExpect(status().isOk()).andExpect(content().string(containsString("Dismissed")))
                .andExpect(content().string(containsString("Snoozed")));
        mvc.perform(get("/alerts/rules").param("code", MILK)).andExpect(status().isOk())
                .andExpect(content().string(containsString("migrated-time")));

        personal.reset();
        migration.afterPropertiesSet();
        assertTrue(rules.rules(MILK).isEmpty());
        assertTrue(events.events(NOW).isEmpty());
        assertEquals(0, count("replenishment_reminders"));
        assertEquals(0, count("reminder_occurrences"));
        assertTrue(catalog.find(MILK).active());
    }

    @Test void upgradesOlderReminderThatPredatesPauseAndHistory() {
        legacyRule(7, false, SNOOZED);
        jdbc.execute("alter table replenishment_reminders drop column paused");
        jdbc.execute("drop table reminder_occurrences");
        try {
            migration.afterPropertiesSet();
            var rule = rules.rules(MILK).getFirst();
            assertTrue(rule.enabled());
            assertEquals(DUE, rule.nextDueAt());
            assertEquals(SNOOZED, rule.snoozedUntil());
            assertTrue(events.events(NOW).isEmpty());
        } finally {
            jdbc.execute("alter table replenishment_reminders add column paused boolean");
        }
    }

    @Test void migratedOccurrenceKeepsCartChoiceAndDismissalAdvancesOriginalInterval() throws Exception {
        legacyRule(7, false, null);
        migration.afterPropertiesSet();
        rules.checkDue();
        rules.checkDue();
        var event = events.events(NOW).getFirst();
        assertEquals(1, events.events(NOW).size());
        assertTrue(event.cartAvailable());
        assertEquals(DUE, event.scheduledDueAt());

        mvc.perform(post("/alerts/product-events/" + event.id() + "/add")).andExpect(redirectedUrl("/alerts"));
        var item = shopping.items().getFirst();
        assertEquals(2, item.quantity());
        assertEquals("AEON", item.selectedRetailerCode());

        mvc.perform(post("/alerts/product-events/" + event.id() + "/snooze")).andExpect(redirectedUrl("/alerts"));
        assertFalse(events.events(NOW).getFirst().cartAvailable());
        assertEquals(NOW.plus(1, ChronoUnit.DAYS), rules.rules(MILK).getFirst().snoozedUntil());
        mvc.perform(get("/alerts")).andExpect(status().isOk())
                .andExpect(content().string(not(containsString("/" + event.id() + "/add"))));

        mvc.perform(post("/alerts/product-events/" + event.id() + "/read")).andExpect(redirectedUrl("/alerts"));
        assertEquals(NOW.plus(7, ChronoUnit.DAYS), rules.rules(MILK).getFirst().nextDueAt());
        assertNull(rules.rules(MILK).getFirst().snoozedUntil());
        assertTrue(events.events(NOW).getFirst().read());
        assertEquals(1, events.events(NOW).size());
    }

    @Test void pinnedUnknownPriceStaysPinnedAndCannotBeAddedUntilEdited() throws Exception {
        legacyRule(7, false, null);
        migration.afterPropertiesSet();
        jdbc.update("update retailer_listings set price = null where product_code = ? and retailer_code = 'AEON'", MILK);
        rules.checkDue();
        var event = events.events(NOW).getFirst();
        mvc.perform(get("/alerts")).andExpect(status().isOk())
                .andExpect(content().string(containsString("No current price for this choice")))
                .andExpect(content().string(not(containsString("/" + event.id() + "/add"))));
        assertThrows(IllegalArgumentException.class, () -> rules.addReminderToCart(event.id()));
        assertTrue(shopping.items().isEmpty());
        var rule = rules.rules(MILK).getFirst();
        mvc.perform(post("/alerts/watch-rules/save").param("code", MILK).param("id", Long.toString(rule.id()))
                        .param("condition", "migrated-time").param("intervalDays", "7")
                        .param("quantity", "3").param("retailerCode", "JASONS"))
                .andExpect(redirectedUrl("/alerts/rules?code=" + MILK));
        var edited = events.events(NOW).getFirst();
        assertEquals("JASONS", edited.cartRetailer());
        assertEquals(3, edited.cartQuantity());
        assertTrue(edited.cartAvailable());
        rules.delete(MILK, rule.id());
        assertTrue(events.events(NOW).getFirst().read());
        assertFalse(events.events(NOW).getFirst().activeReminder());
    }

    @Test void failedHistoryInsertRollsBackMigratedRulesAndKeepsSourceRecords() {
        legacyRule(7, false, null);
        legacyEvent(15, 7, null, null);
        jdbc.execute("alter table product_target_events add constraint prevent_migration check (legacy_occurrence_id <> 15)");
        try {
            assertThrows(DataAccessException.class, migration::afterPropertiesSet);
            assertEquals(1, count("replenishment_reminders"));
            assertEquals(1, count("reminder_occurrences"));
            assertTrue(rules.allRules().isEmpty());
            assertTrue(events.events(NOW).isEmpty());
        } finally {
            jdbc.execute("alter table product_target_events drop constraint prevent_migration");
        }
        migration.afterPropertiesSet();
        assertEquals(1, rules.rules(MILK).size());
        assertEquals(1, events.events(NOW).size());
    }

    private void legacyRule(long id, boolean paused, Instant snoozed) {
        jdbc.update("""
                insert into replenishment_reminders
                    (id, product_code, quantity, interval_days, selected_retailer_code, next_due_at, snoozed_until, paused)
                values (?, ?, 2, 7, 'AEON', ?, ?, ?)
                """, id, MILK, offset(DUE), offset(snoozed), paused);
    }

    private void legacyEvent(long id, long ruleId, Instant read, Instant snoozed) {
        jdbc.update("""
                insert into reminder_occurrences
                    (id, reminder_id, product_code, quantity, retailer_code, due_at, created_at, read_at, snoozed_until)
                values (?, ?, ?, 2, 'AEON', ?, ?, ?, ?)
                """, id, ruleId, MILK, offset(DUE), offset(DUE), offset(read), offset(snoozed));
    }

    private static OffsetDateTime offset(Instant value) {
        return value == null ? null : value.atOffset(ZoneOffset.UTC);
    }

    private int count(String table) {
        return jdbc.queryForObject("select count(*) from " + table, Integer.class);
    }
}
